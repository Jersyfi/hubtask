// Fails when src/ holds anything but the generated client, or the client lost its licence line.
//
// The SDK is what a third party takes; everything in it is generated from the contract or is the
// header the generator writes. A hand-written file here would be the start of a second client,
// and a client without its Apache-2.0 line is one whose terms a consumer has to take on trust
// (ADR-0059 §6).

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.join(packageRoot, 'src');

const problems = [];
for (const entry of fs.readdirSync(source)) {
  if (entry !== 'client.gen.ts') {
    problems.push(`src/${entry}: only the generated client belongs here (tools/sdkgen, make generate)`);
    continue;
  }
  const content = fs.readFileSync(path.join(source, entry), 'utf8');
  const head = content.split('\n').slice(0, 12).join('\n');
  if (!head.includes('Code generated by tools/sdkgen')) {
    problems.push(`src/${entry}: does not say it is generated - run make generate`);
  }
  if (!head.includes('SPDX-License-Identifier: Apache-2.0')) {
    problems.push(`src/${entry}: the Apache-2.0 header is missing (ADR-0059 §6)`);
  }
}

if (problems.length > 0) {
  for (const problem of problems) console.error(problem);
  process.exit(1);
}
console.log('sdk-typescript: src/ holds the generated client and nothing else');
