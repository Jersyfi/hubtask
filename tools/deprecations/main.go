// Command deprecations writes the table of deprecated request fields from api/openapi.yaml (SC-28).
//
// The contract marks a field `deprecated: true` with `x-deprecated-since`, `x-removed-in`,
// `x-replaced-by` and an optional `x-sunset`; this reads every operation whose JSON request body
// carries such a field and writes the table the REST adapter announces them from - the
// `Deprecation` and `Sunset` headers, and the manifest's `deprecations`. Generated rather than
// written, so the announcement and the specification cannot drift (ADR-0004).
//
// **A mark it cannot announce fails it.** Only a top-level property of a component schema that a
// JSON request body references can be announced; a deprecated parameter, operation, nested or
// response-only member would be in the specification and nowhere else, so it stops `make generate`
// rather than going unsaid.
//
// Usage: deprecations <openapi.yaml> <out.go>
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"slices"
	"sort"
	"strings"
	"time"

	"gopkg.in/yaml.v3"
)

type document struct {
	// A path item holds its operations by method beside a list of shared parameters, so each entry
	// is decoded only when it is an operation.
	Paths      map[string]map[string]yaml.Node `yaml:"paths"`
	Components struct {
		Schemas map[string]schema `yaml:"schemas"`
	} `yaml:"components"`
}

type operation struct {
	OperationID string `yaml:"operationId"`
	RequestBody struct {
		Content map[string]struct {
			Schema schema `yaml:"schema"`
		} `yaml:"content"`
	} `yaml:"requestBody"`
}

type schema struct {
	Ref        string            `yaml:"$ref"`
	Properties map[string]schema `yaml:"properties"`
	Deprecated bool              `yaml:"deprecated"`
	Since      string            `yaml:"x-deprecated-since"`
	RemovedIn  string            `yaml:"x-removed-in"`
	Sunset     string            `yaml:"x-sunset"`
	ReplacedBy []string          `yaml:"x-replaced-by"`
}

type entry struct {
	OperationID, Method, Path, Field, Since, RemovedIn, Sunset string
	ReplacedBy                                                 []string
}

var methods = []string{"get", "put", "post", "patch", "delete"}

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: deprecations <openapi.yaml> <out.go>")
		os.Exit(2)
	}
	raw, err := os.ReadFile(os.Args[1]) //nolint:gosec // G703: the file the Makefile names; reading it is the job
	if err != nil {
		fail(err)
	}
	entries, err := table(raw)
	if err != nil {
		fail(err)
	}

	var out bytes.Buffer
	out.WriteString("// Code generated by tools/deprecations from api/openapi.yaml. DO NOT EDIT.\n\n")
	out.WriteString("package rest\n\n")
	out.WriteString("// deprecatedFields is every deprecated request field the contract declares, in a stable order.\n")
	out.WriteString("var deprecatedFields = []deprecatedField{\n")
	for _, e := range entries {
		fmt.Fprintf(&out, "\t{OperationID: %q, Method: %q, Path: %q, Field: %q, Since: %q, RemovedIn: %q, Sunset: %q, ReplacedBy: %#v},\n",
			e.OperationID, e.Method, e.Path, e.Field, e.Since, e.RemovedIn, e.Sunset, e.ReplacedBy)
	}
	out.WriteString("}\n")
	formatted, err := format.Source(out.Bytes())
	if err != nil {
		fail(err)
	}
	if err := os.WriteFile(os.Args[2], formatted, 0o600); err != nil { //nolint:gosec // G703: the output the Makefile names
		fail(err)
	}
}

// table reads the deprecated request fields of a specification, sorted, or refuses a mark it cannot
// announce or one that is incomplete.
func table(raw []byte) ([]entry, error) {
	var doc document
	if err := yaml.Unmarshal(raw, &doc); err != nil {
		return nil, err
	}
	var root yaml.Node
	if err := yaml.Unmarshal(raw, &root); err != nil {
		return nil, err
	}
	marked := map[string]bool{}
	markedAt(&root, nil, marked)

	var entries []entry
	announced := map[string]bool{}
	for path, ops := range doc.Paths {
		for _, method := range methods {
			node, ok := ops[method]
			if !ok {
				continue
			}
			var op operation
			if err := node.Decode(&op); err != nil {
				return nil, fmt.Errorf("%s %s: %w", method, path, err)
			}
			body, ok := op.RequestBody.Content["application/json"]
			if !ok || body.Schema.Ref == "" {
				continue // an inline body's deprecated member is refused below, as unannounceable
			}
			schemaName := strings.TrimPrefix(body.Schema.Ref, "#/components/schemas/")
			for name, property := range doc.Components.Schemas[schemaName].Properties {
				if !property.Deprecated {
					continue
				}
				if err := complete(property); err != nil {
					return nil, fmt.Errorf("%s.%s: %w", schemaName, name, err)
				}
				announced[schemaName+"."+name] = true
				entries = append(entries, entry{
					OperationID: op.OperationID, Method: strings.ToUpper(method), Path: path, Field: name,
					Since: property.Since, RemovedIn: property.RemovedIn, Sunset: property.Sunset,
					ReplacedBy: property.ReplacedBy,
				})
			}
		}
	}
	for _, at := range sortedKeys(marked) {
		if !announced[at] {
			return nil, fmt.Errorf("%s is marked deprecated where nothing can announce it: only a "+
				"top-level property of a component schema a JSON request body references is", at)
		}
	}
	sort.Slice(entries, func(i, j int) bool {
		if entries[i].Path != entries[j].Path {
			return entries[i].Path < entries[j].Path
		}
		if entries[i].Method != entries[j].Method {
			return entries[i].Method < entries[j].Method
		}
		return entries[i].Field < entries[j].Field
	})

	return entries, nil
}

// complete refuses a mark without its day, its major version or what replaces it, and a day that is
// not one: a date that does not parse would drop the header and the manifest's day without a word.
func complete(property schema) error {
	if _, err := time.Parse(time.DateOnly, property.Since); err != nil {
		return fmt.Errorf("x-deprecated-since %q is not a day: %w", property.Since, err)
	}
	if !strings.HasPrefix(property.RemovedIn, "v") {
		return fmt.Errorf("x-removed-in %q is not a major version", property.RemovedIn)
	}
	if len(property.ReplacedBy) == 0 {
		return fmt.Errorf("x-replaced-by names nothing")
	}
	if property.Sunset != "" {
		if _, err := time.Parse(time.DateOnly, property.Sunset); err != nil {
			return fmt.Errorf("x-sunset %q is not a day: %w", property.Sunset, err)
		}
	}
	return nil
}

// markedAt collects every `deprecated: true` in the document, by where it sits. A property of a
// component schema is "Schema.field"; anything else is its whole path, which nothing announces.
func markedAt(node *yaml.Node, path []string, marked map[string]bool) {
	switch node.Kind {
	case yaml.DocumentNode:
		for _, child := range node.Content {
			markedAt(child, path, marked)
		}
	case yaml.SequenceNode:
		for i, child := range node.Content {
			markedAt(child, append(slices.Clone(path), fmt.Sprint(i)), marked)
		}
	case yaml.MappingNode:
		for i := 0; i+1 < len(node.Content); i += 2 {
			key, value := node.Content[i].Value, node.Content[i+1]
			if key == "deprecated" && value.Value == "true" {
				if len(path) == 5 && path[0] == "components" && path[1] == "schemas" && path[3] == "properties" {
					marked[path[2]+"."+path[4]] = true
				} else {
					marked[strings.Join(path, "/")] = true
				}
			}
			markedAt(value, append(slices.Clone(path), key), marked)
		}
	}
}

func sortedKeys(set map[string]bool) []string {
	keys := make([]string, 0, len(set))
	for key := range set {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "deprecations:", err)
	os.Exit(1)
}
