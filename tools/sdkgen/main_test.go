func TestTheRealContractGenerates(t *testing.T) {
	raw, err := os.ReadFile("../../api/openapi.yaml")
	if err != nil {
		t.Skip("no specification beside the tool")
	}
	doc, err := Read(raw)
	if err != nil {
		t.Fatal(err)
	}
	ts := GenerateTypeScript(doc)
	client, _ := GeneratePython(doc)
	for _, op := range doc.Operations {
		if !strings.Contains(ts, "  "+op.ID+"(") {
			t.Errorf("%s has no TypeScript method", op.ID)
		}
		if !strings.Contains(client, "    def "+pyName(op.ID)+"(") {
			t.Errorf("%s has no Python method", op.ID)
		}
	}
}
