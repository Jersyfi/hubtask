func read(t *testing.T) *Document {
	t.Helper()
	doc, err := Read([]byte(fixture))
	if err != nil {
		t.Fatal(err)
	}
	return doc
}

func TestTheModelReadsOperationsInOrderWithTheirParts(t *testing.T) {
	doc := read(t)
	ids := []string{}
	for _, op := range doc.Operations {
		ids = append(ids, op.ID)
	}
	if got := strings.Join(ids, ","); got != "createItem,getItem,trashItem,completeItem,feed" {
		t.Errorf("operations = %s", got)
	}
	get := doc.Operations[1]
	if len(get.PathParams) != 1 || get.PathParams[0].Name != "itemId" || !get.PathParams[0].Required {
		t.Errorf("the shared path parameter did not reach the operation: %+v", get.PathParams)
	}
	if len(get.Query) != 1 || get.Query[0].Type != "list[str]" {
		t.Errorf("query = %+v", get.Query)
	}
	create := doc.Operations[0]
	if create.Body == nil || create.Body.SchemaName != "ItemCreate" || len(create.Headers) != 1 {
		t.Errorf("create = %+v", create)
	}
	if create.Answer == nil || create.Answer.Status != "201" || create.Answer.SchemaName != "Item" {
		t.Errorf("answer = %+v", create.Answer)
	}
	if !doc.Operations[2].Deprecated || doc.Operations[2].Answer.ContentType != "" {
		t.Errorf("trash = %+v", doc.Operations[2])
	}
	if !doc.Operations[3].Public {
		t.Error("security: [] should mark the operation public")
	}
}

func TestTheTypeScriptClientIsTypedAgainstTheOperations(t *testing.T) {
	ts := GenerateTypeScript(read(t))
	for _, want := range []string{
		"// Code generated by tools/sdkgen",
		`createItem(body: NonNullable<operations["createItem"]['requestBody']>['content']["application/json"], options: CallOptions & { readonly idempotencyKey?: string } = {}): Promise<operations["createItem"]['responses'][201]['content']["application/json"]>`,
		`getItem(itemId: string, options: CallOptions & { readonly query?: NonNullable<operations["getItem"]['parameters']['query']> } = {}): Promise<operations["getItem"]['responses'][200]['content']["application/json"]>`,
		`trashItem(itemId: string, options: CallOptions = {}): Promise<void>`,
		"   * @deprecated",
		`feed(token: string, options: CallOptions = {}): Promise<Response>`,
		`this.call("POST", "/items/{itemId}:complete", { "itemId": itemId }, undefined, {  }, undefined, "none", undefined, "json", options.signal)`,
	} {
		if !strings.Contains(ts, want) {
			t.Errorf("missing in the TypeScript client:\n%s", want)
		}
	}
}

