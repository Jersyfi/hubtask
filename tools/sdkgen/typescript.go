// The TypeScript client: one class over `fetch`, one method per operation, typed against the
// `operations` types openapi-typescript already generates into dist/schema.d.ts. No runtime
// dependency - a library that pulls a tree into somebody's project is a library they audit
// before they adopt (milestone-0.9.0.md, decision 3).

const tsHeader = `// Code generated by tools/sdkgen from api/openapi.yaml - DO NOT EDIT.
//
// The TypeScript client for the Hubtask API (P-03, ADR-0057). Regenerated by ` + "`make generate`" + `;
// the specification is the source and this is the result (ADR-0004). One method per operation,
// typed against the ` + "`operations`" + ` types in dist/schema.d.ts, over the platform's ` + "`fetch`" + ` and
// nothing else.
//
// SPDX-License-Identifier: BUSL-1.1

import type { components, operations } from '../dist/schema.js';

/** A problem document (RFC 9457): every refusal of the contract is one. */
export type Problem = components['schemas']['Problem'];

/** The client's options. The address is the API root: ` + "`https://<host>/api/v1`" + `. */
export interface ClientOptions {
  readonly baseUrl: string;
  /** The bearer - a personal access token, a service account token or an OIDC access token - or a function that answers the current one. */
  readonly token?: string | (() => string | undefined | Promise<string | undefined>);
  /** The platform's fetch, replaceable for a test or a runtime that names it differently. */
  readonly fetch?: typeof fetch;
  /** Headers sent on every request, such as a user agent. */
  readonly headers?: Readonly<Record<string, string>>;
}

/** A refusal: the status and the problem document the server answered. */
export class ProblemError extends Error {
  readonly status: number;
  readonly problem: Problem;
  constructor(status: number, problem: Problem) {
    super(problem.detail_code ? ` + "`hubtask: ${status} ${problem.code} (${problem.detail_code})`" + ` : ` + "`hubtask: ${status} ${problem.code}`" + `);
    this.name = 'ProblemError';
    this.status = status;
    this.problem = problem;
  }
}

/** Options every method takes beside its own: an abort signal. */
export interface CallOptions {
  readonly signal?: AbortSignal;
}

type BodyKind = 'json' | 'raw' | 'none';
type AnswerKind = 'json' | 'raw' | 'void';

export class HubtaskClient {
  readonly #options: ClientOptions;

  constructor(options: ClientOptions) {
    this.#options = options;
  }

  /**
   * One request. Every generated method comes here: the path template is filled from ` + "`path`" + `,
   * the query is appended with ` + "`undefined`" + ` values left out, the bearer is added, and a non-2xx
   * answer becomes a ProblemError - a body that is not a problem document (a proxy's HTML) still
   * becomes one, with the status and an empty code, so that a caller has one shape to handle.
   */
  protected async call<T>(
    method: string,
    template: string,
    path: Readonly<Record<string, string | number>>,
    query: Readonly<Record<string, unknown>> | undefined,
    headers: Readonly<Record<string, string | undefined>>,
    body: unknown,
    bodyKind: BodyKind,
    contentType: string | undefined,
    answer: AnswerKind,
    signal: AbortSignal | undefined,
  ): Promise<T> {
    let url = template.replace(/\{([^}]+)\}/g, (_, name: string) => encodeURIComponent(String(path[name] ?? '')));
    const search = new URLSearchParams();
    for (const [key, value] of Object.entries(query ?? {})) {
      if (value === undefined || value === null) continue;
      if (Array.isArray(value)) for (const each of value) search.append(key, String(each));
      else search.set(key, String(value));
    }
    const qs = search.toString();
    if (qs) url += ` + "`?${qs}`" + `;

    const sent = new Headers(this.#options.headers);
    if (answer === 'json') sent.set('Accept', 'application/json, application/problem+json');
    const token = typeof this.#options.token === 'function' ? await this.#options.token() : this.#options.token;
    if (token) sent.set('Authorization', ` + "`Bearer ${token}`" + `);
    for (const [key, value] of Object.entries(headers)) if (value !== undefined) sent.set(key, value);

    let payload: BodyInit | undefined;
    if (bodyKind === 'json') {
      sent.set('Content-Type', contentType ?? 'application/json');
      payload = JSON.stringify(body);
    } else if (bodyKind === 'raw') {
      if (contentType) sent.set('Content-Type', contentType);
      payload = body as BodyInit;
    }

    const doFetch = this.#options.fetch ?? fetch;
    const response = await doFetch(this.#options.baseUrl + url, { method, headers: sent, body: payload, signal });
    if (!response.ok) {
      let problem: Problem = { status: response.status, code: '' };
      try {
        const parsed = (await response.json()) as Partial<Problem>;
        problem = { ...problem, ...parsed, status: parsed.status ?? response.status, code: parsed.code ?? '' };
      } catch {
        // Not a problem document; the status is the whole answer.
      }
      throw new ProblemError(response.status, problem);
    }
    if (answer === 'void') return undefined as T;
    if (answer === 'raw') return response as T;
    if (response.status === 204) return undefined as T;
    return (await response.json()) as T;
  }
`

// tsOptionName is the option key a header parameter is set through.
func tsOptionName(header string) string {
	switch header {
	case "Idempotency-Key":
		return "idempotencyKey"
	case "If-Match":
		return "ifMatch"
	case "X-Hubtask-Step-Up":
		return "stepUp"
	case "Last-Event-ID":
		return "lastEventId"
	}
	return camel(strings.ReplaceAll(header, "-", "_"))
}

func camel(name string) string {
	parts := strings.FieldsFunc(name, func(r rune) bool { return r == '_' || r == '-' })
	for i := range parts {
		if i == 0 {
			parts[i] = strings.ToLower(parts[i][:1]) + parts[i][1:]
		} else {
			parts[i] = strings.ToUpper(parts[i][:1]) + parts[i][1:]
		}
	}
	return strings.Join(parts, "")
}

func isJSON(contentType string) bool {
	return contentType == "application/json" || strings.HasSuffix(contentType, "+json")
}

// GenerateTypeScript writes the client.
func GenerateTypeScript(doc *Document) string {
	var b strings.Builder
	b.WriteString(tsHeader)
	for _, op := range doc.Operations {
		b.WriteString("\n")
		writeTSDoc(&b, op)
		args := []string{}
		pathObject := []string{}
		for _, p := range op.PathParams {
			name := camel(p.Name)
			args = append(args, fmt.Sprintf("%s: string", name))
			pathObject = append(pathObject, fmt.Sprintf("%q: %s", p.Name, name))
		}
		bodyKind, bodyType := "none", ""
		if op.Body != nil {
			if isJSON(op.Body.ContentType) {
				bodyKind = "json"
				bodyType = fmt.Sprintf("NonNullable<operations[%q]['requestBody']>['content'][%q]", op.ID, op.Body.ContentType)
			} else {
				bodyKind = "raw"
				bodyType = "BodyInit"
			}
			args = append(args, "body: "+bodyType)
		}
		options := []string{}
		if len(op.Query) > 0 {
			options = append(options, fmt.Sprintf("readonly query?: NonNullable<operations[%q]['parameters']['query']>", op.ID))
		}
		for _, h := range op.Headers {
			options = append(options, fmt.Sprintf("readonly %s?: string", tsOptionName(h.Name)))
		}
		optionsType := "CallOptions"
		if len(options) > 0 {
			optionsType = "CallOptions & { " + strings.Join(options, "; ") + " }"
		}
		args = append(args, "options: "+optionsType+" = {}")

		answerKind, answerType := "void", "void"
		if op.Answer != nil && op.Answer.ContentType != "" {
			if isJSON(op.Answer.ContentType) {
				answerKind = "json"
				answerType = fmt.Sprintf("operations[%q]['responses'][%s]['content'][%q]", op.ID, op.Answer.Status, op.Answer.ContentType)
			} else {
				answerKind = "raw"
				answerType = "Response"
			}
		}

		headers := []string{}
		for _, h := range op.Headers {
			headers = append(headers, fmt.Sprintf("%q: options.%s", h.Name, tsOptionName(h.Name)))
		}
		query := "undefined"
		if len(op.Query) > 0 {
			query = "options.query"
		}
		bodyArg := "undefined"
		if op.Body != nil {
			bodyArg = "body"
		}
		contentType := "undefined"
		if op.Body != nil {
			contentType = fmt.Sprintf("%q", op.Body.ContentType)
		}
		fmt.Fprintf(&b, "  %s(%s): Promise<%s> {\n", op.ID, strings.Join(args, ", "), answerType)
		fmt.Fprintf(&b, "    return this.call(%q, %q, { %s }, %s, { %s }, %s, %q, %s, %q, options.signal);\n  }\n",
			op.Method, op.Path, strings.Join(pathObject, ", "), query, strings.Join(headers, ", "), bodyArg, bodyKind, contentType, answerKind)
	}
	b.WriteString("}\n")
	return b.String()
}

func writeTSDoc(b *strings.Builder, op Operation) {
	line := op.Summary
	if line == "" {
		line = op.Method + " " + op.Path
	}
	fmt.Fprintf(b, "  /** %s", strings.ReplaceAll(line, "*/", "* /"))
	if op.Deprecated {
		b.WriteString("\n   * @deprecated")
	}
	if op.Public {
		b.WriteString("\n   * Public: sent without a bearer where the client holds none.")
	}
	b.WriteString(" */\n")
}
